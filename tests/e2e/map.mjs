// The nearby pandits map: markers, marker cards, zoom, radius, list view, location and labelling.
import { BASE, KEY, launch, open, reporter, writeState } from "./helpers.mjs"

const { browser, ctx, page, errors } = await launch()
page.setDefaultTimeout(9000)
const { check, section, finish } = reporter(errors, "Map")
const btn = (name) => page.getByRole("button", { name, exact: true })
const pins = page.locator(".pandit-pin")
const label = page.locator(".map-label")
const state = () => page.evaluate((k) => JSON.parse(localStorage.getItem(k)), KEY)
const guard = async (name, fn) => {
  try {
    await fn()
  } catch (e) {
    check(`${name} (no crash)`, false, e.message.split("\n").slice(0, 2).join(" ").slice(0, 220))
  }
}
const ready = async () => {
  await page.waitForSelector(".leaflet-container")
  await page.waitForTimeout(400)
}
const resultNames = () => page.locator(".result-list .pandit-card h3").allTextContents()

section("A real map")
await guard("map", async () => {
  await open(page, { page: "pandits" })
  await ready()
  check("a Leaflet map replaces the decorative pattern", (await page.locator(".map-grid").count()) === 0 && (await page.locator(".leaflet-container").count()) === 1)
  check("it uses OpenStreetMap tiles", (await page.locator(".leaflet-tile-pane img").first().getAttribute("src")).startsWith("https://tile.openstreetmap.org/"))
  check("OpenStreetMap is credited", (await page.locator(".leaflet-control-attribution").textContent()).includes("OpenStreetMap contributors"))
  check("your location has its own marker", (await page.locator(".user-pin").count()) === 1)
  check("there is one marker per pandit in the results", (await pins.count()) === (await resultNames()).length, `${await pins.count()} markers, ${(await resultNames()).length} results`)
  const prices = await pins.allTextContents()
  check("each marker shows a price", prices.every((t) => /^₹\d\.\dk$/.test(t)), prices.join(", "))
  check("the radius circle is drawn", (await page.locator(".leaflet-overlay-pane path").count()) === 1)
  check("it is clearly labelled as demo locations", (await label.textContent()).includes("Demo locations") && (await label.textContent()).includes("not real addresses"))
  check("the count and radius are shown", /^\d+ pandits? nearby$/.test(await label.locator("b").textContent()) && (await label.textContent()).includes("Within 25 km of your area (Gurugram)"), await label.locator("b").textContent())
})

section("Marker card")
await guard("popup", async () => {
  const raghav = page.locator(".pandit-pin").filter({ hasText: "₹3.5k" }).first()
  await raghav.click()
  const pop = page.locator(".map-popup")
  check("clicking a marker opens a card", await pop.isVisible())
  check("the card shows the name", (await pop.locator("b").first().textContent()) === "Acharya Raghav Sharma")
  check("an avatar stands in for a photo", (await pop.locator(".map-popup-avatar").textContent()) === "RS")
  check("the rating", (await pop.locator(".map-popup-rating").textContent()).includes("4.9"))
  check("the price", (await pop.locator(".map-popup-foot b").textContent()) === "₹3,500")
  check("the distance, marked as a demo location", /\d+\.\d km away · demo location/.test(await pop.locator(".map-popup-meta").textContent()))
  await pop.getByRole("button", { name: "View profile" }).click()
  check("View profile opens that pandit", page.url() === BASE + "/pandits/raghav" && (await page.locator(".profile-main h1").textContent()) === "Acharya Raghav Sharma")
  await page.goBack()
  await ready()
  check("Back returns to the map", (await page.locator(".leaflet-container").count()) === 1)
  await page.locator(".pandit-pin").first().focus()
  await page.keyboard.press("Enter")
  check("markers also open with the keyboard", await page.locator(".map-popup").isVisible())
})

section("Zoom")
await guard("zoom", async () => {
  await page.keyboard.press("Escape")
  const gap = () => page.evaluate(() => {
    const [a, b] = [...document.querySelectorAll(".pandit-pin")].map((e) => e.getBoundingClientRect())
    return Math.hypot(a.left - b.left, a.top - b.top)
  })
  const before = await gap()
  await page.getByRole("button", { name: "Zoom in" }).click()
  await page.waitForTimeout(400)
  const zoomedIn = await gap()
  check("Zoom in spreads markers apart", zoomedIn > before * 1.5, `${before.toFixed(0)} -> ${zoomedIn.toFixed(0)} px`)
  await page.getByRole("button", { name: "Zoom out" }).click()
  await page.getByRole("button", { name: "Zoom out" }).click()
  await page.waitForTimeout(400)
  check("Zoom out brings them closer", (await gap()) < zoomedIn / 2, `${(await gap()).toFixed(0)} px`)
  check("the page does not scroll-zoom the map by accident", (await page.evaluate(() => document.querySelector(".leaflet-container").classList.contains("leaflet-touch-zoom"))) !== null)
})

section("Radius")
await guard("radius", async () => {
  await open(page, { page: "pandits" })
  await ready()
  const count = async () => Number((await label.locator("b").textContent()).split(" ")[0])
  const at25 = await count()
  await page.getByLabel("Search radius").selectOption("50")
  await page.waitForTimeout(300)
  check("a larger radius finds more pandits", (await count()) > at25 && (await label.textContent()).includes("Within 50 km"), `${at25} -> ${await count()}`)
  await page.getByLabel("Search radius").selectOption("10")
  await page.waitForTimeout(300)
  check("a smaller radius finds fewer", (await count()) <= at25 && (await label.textContent()).includes("Within 10 km"), String(await count()))
  check("pandits outside the radius are shown faded", (await page.locator(".pandit-pin.far").count()) === (await pins.count()) - (await count()))
})

section("List view")
await guard("list", async () => {
  await page.getByLabel("Search radius").selectOption("50")
  await btn("List").click()
  check("List hides the map", (await page.locator(".leaflet-container").count()) === 0)
  const rows = page.locator(".map-list-row")
  check("List shows the nearby pandits", (await rows.count()) === Number((await label.locator("b").textContent()).split(" ")[0]))
  const km = (await rows.locator("small").allTextContents()).map((t) => parseFloat(t))
  check("sorted nearest first", km.every((v, i) => i === 0 || v >= km[i - 1]), km.join(", "))
  check("each row shows distance and price", (await rows.first().locator("small").textContent()).includes("km away · from ₹"))
  check("Map and List show which is active", (await btn("List").getAttribute("aria-pressed")) === "true" && (await btn("Map").getAttribute("aria-pressed")) === "false")
  await page.getByLabel("Search radius").selectOption("10")
  await page.waitForTimeout(200)
  if ((await rows.count()) === 0) check("an empty radius explains itself", await page.getByText("No pandits within 10 km").isVisible())
  await page.getByLabel("Search radius").selectOption("25")
  await rows.first().getByRole("button", { name: "View profile" }).click()
  check("View profile from the list opens that pandit", page.url().startsWith(BASE + "/pandits/") && (await page.locator(".profile-main h1").count()) === 1)
  await page.goBack()
  await page.waitForSelector(".map-card")
  await btn("Map").click()
  await ready()
  check("Map brings the map back", (await pins.count()) > 0)
})

section("Filters reach the map")
await guard("filters", async () => {
  await page.getByRole("button", { name: "Choose language" }).click()
  await page.getByRole("menuitem", { name: "Gujarati" }).click()
  await page.waitForTimeout(300)
  check("filtering the results filters the markers", (await pins.count()) === 1 && (await resultNames()).length === 1)
  await page.getByRole("button", { name: "Choose language" }).click()
  await page.getByRole("menuitem", { name: "Any language" }).click()
})

section("Your location")
await guard("geolocation", async () => {
  await ctx.grantPermissions(["geolocation"], { origin: BASE })
  await ctx.setGeolocation({ latitude: 28.5355, longitude: 77.391 })
  await open(page, { page: "pandits" })
  await ready()
  await btn("Use my location").click()
  await page.waitForTimeout(500)
  check("your real location is used when you allow it", (await label.textContent()).includes("Within 25 km of your location"))
  await page.locator(".user-pin").hover()
  check("its marker says Your location", (await page.locator(".map-tooltip").textContent()) === "Your location")
  check("it is never saved", !JSON.stringify(await state()).includes("77.391"))
  await btn("Use demo location").click()
  await page.waitForTimeout(300)
  check("you can switch back to the demo location", (await label.textContent()).includes("your area (Gurugram)"))
  await ctx.clearPermissions()
  await page.evaluate(() => {
    navigator.geolocation.getCurrentPosition = (_ok, fail) => fail({ code: 1, message: "denied" })
  })
  await btn("Use my location").click()
  check("a refusal is explained and the demo location stays", (await page.getByText("Location access was not allowed").count()) === 1 && (await label.textContent()).includes("your area (Gurugram)"))
})

section("Safety and edge cases")
await guard("edge", async () => {
  await open(page, {})
  const s = await state()
  const odd = { ...s.pandits[0], id: "x1", name: '<img src=x onerror="window.__hacked=1">Pandit Test', city: "Gurugram", initials: "PT" }
  const nowhere = { ...s.pandits[0], id: "x2", name: "Pandit Elsewhere", city: "Lucknow", initials: "PE" }
  await writeState(page, { pandits: [...s.pandits, odd, nowhere] })
  await page.goto(BASE + "/pandits")
  await ready()
  await page.getByLabel("Search radius").selectOption("50")
  await page.waitForTimeout(300)
  const pin = page.locator(".pandit-pin").filter({ hasText: "₹3.5k" })
  for (let i = 0; i < (await pin.count()); i++) {
    await pin.nth(i).click()
    if ((await page.locator(".map-popup b").first().textContent()).includes("Pandit Test")) break
  }
  check("names are shown as text, never run as code", (await page.locator(".map-popup img").count()) === 0 && !(await page.evaluate(() => window.__hacked)))
  check("a pandit in a city without map data is counted, not placed", (await label.textContent()).includes("1 without a map location"))
  await writeState(page, { draft: { ...s.draft, city: "Lucknow" } })
  await page.goto(BASE + "/pandits")
  await ready()
  check("an unknown home city falls back to a labelled demo area", (await label.textContent()).includes("your area (Gurugram)"))
})

section("Phone")
await guard("phone", async () => {
  await page.setViewportSize({ width: 390, height: 844 })
  await open(page, { page: "pandits" })
  await ready()
  const box = await page.locator(".map-card").boundingBox()
  check("the map shows on a phone", box.height >= 400 && box.width <= 390, JSON.stringify(box))
  check("it comes before the list", box.y < (await page.locator(".result-list").boundingBox()).y)
  check("no sideways scrolling", (await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)) === 0)
  await page.locator(".pandit-pin").first().click()
  const pop = await page.locator(".map-popup").boundingBox()
  check("a marker card fits the screen", pop.x >= 0 && pop.x + pop.width <= 390, JSON.stringify(pop))
  await page.keyboard.press("Escape")
  await btn("List").click()
  check("List works on a phone", (await page.locator(".map-list-row").count()) > 0)
  await page.setViewportSize({ width: 900, height: 800 })
  await btn("Map").click()
  await ready()
  check("the map shows on a tablet", (await page.locator(".map-card").boundingBox()).height >= 400)
})

finish()
await browser.close()
