// The notification bell: badge, list, navigation, mark as read, and closing behaviour.
import { BASE, KEY, launch, open, reporter } from "./helpers.mjs"

const { browser, page, errors } = await launch()
page.setDefaultTimeout(9000)
const { check, section, finish } = reporter(errors, "Notifications")
const bell = page.getByRole("button", { name: /^Notifications,/ })
const badge = page.locator(".bell-badge")
const list = page.getByRole("menu", { name: "Notifications" })
const items = list.getByRole("menuitem")
const state = () => page.evaluate((k) => JSON.parse(localStorage.getItem(k)), KEY)
const unread = async () => Number(/(\d+) unread/.exec(await bell.getAttribute("aria-label"))[1])
const urlIs = (path) => page.url() === BASE + path
const guard = async (name, fn) => {
  try {
    await fn()
  } catch (e) {
    check(`${name} (no crash)`, false, e.message.split("\n").slice(0, 2).join(" ").slice(0, 220))
  }
}

section("The bell")
await guard("bell", async () => {
  await open(page, { signedIn: true, page: "dashboard" })
  check("a bell icon replaces the plain number", (await bell.locator("svg").count()) === 1 && (await page.locator(".top-profile .notification").count()) === 0)
  check("it sits at the top right", await page.evaluate(() => {
    const r = document.querySelector(".bell-button").getBoundingClientRect()
    return r.right > innerWidth - 250 && r.top < 60
  }))
  check("the badge shows the unread count", (await badge.textContent()) === "2" && (await unread()) === 2, await badge.textContent())
  const pos = await page.evaluate(() => {
    const b = document.querySelector(".bell-button").getBoundingClientRect()
    const d = document.querySelector(".bell-badge").getBoundingClientRect()
    return { right: d.right >= b.right - 6, top: d.top <= b.top + 6 }
  })
  check("the badge sits at the bell's top right", pos.right && pos.top, JSON.stringify(pos))
  check("the badge uses the burgundy colour", (await badge.evaluate((e) => getComputedStyle(e).backgroundColor)) === "rgb(118, 47, 56)")
})

section("Opening and closing")
await guard("open close", async () => {
  await bell.click()
  check("clicking the bell opens the list", await list.isVisible())
  check("the bell reports it is open", (await bell.getAttribute("aria-expanded")) === "true")
  await bell.click()
  check("clicking the bell again closes it", (await list.count()) === 0)
  await bell.click()
  await page.mouse.click(600, 600)
  check("clicking outside closes it", (await list.count()) === 0)
  await bell.click()
  await page.keyboard.press("Escape")
  check("Escape closes it", (await list.count()) === 0)
  await bell.click()
  await list.locator(".notices-head").click()
  check("clicking inside the list keeps it open", await list.isVisible())
})

section("Each notification")
await guard("items", async () => {
  const first = items.first()
  check("shows a title", (await first.locator("b").textContent()) === "New message")
  check("shows the message", (await first.textContent()).includes("Acharya Raghav sent you a new message"))
  check("shows a date and time", /^(Today|Yesterday|\d+ \w+), \d+:\d\d (AM|PM)$/.test(await first.locator("small").textContent()), await first.locator("small").textContent())
  check("unread ones are marked", (await list.locator(".notice.unread").count()) === 2 && (await list.locator(".notice.unread > i").count()) === 2)
  await page.keyboard.press("Escape")
})

section("Navigation and read state")
await guard("message notice", async () => {
  await bell.click()
  await items.filter({ hasText: "New message" }).click()
  check("a new message opens Messages", urlIs("/account/messages"))
  check("with that conversation open", (await page.locator(".chat-person b").textContent()) === "Acharya Raghav Sharma")
  check("the list closes", (await list.count()) === 0)
  check("the count goes down by one", (await unread()) === 1 && (await badge.textContent()) === "1")
  await bell.click()
  check("that notice now looks read", !(await items.filter({ hasText: "New message" }).getAttribute("class")).includes("unread"))
  await page.keyboard.press("Escape")
  await page.reload()
  await page.waitForSelector(".app-shell")
  check("read state survives a refresh", (await unread()) === 1)
})
await guard("accepted notice", async () => {
  await bell.click()
  await items.filter({ hasText: "Booking accepted" }).click()
  check("an accepted booking opens its payment page", urlIs("/account/bookings/PN-2501-0104/pay") && (await page.getByText("Payment details").count()) === 1, page.url().replace(BASE, ""))
  check("that notice is now read", (await state()).notices.filter((n) => n.role === "customer").every((n) => n.read))
  await page.getByLabel(/^\s*UPI ID/).fill("demo@upi")
  await page.getByRole("button", { name: /demo payment/ }).click()
  await page.getByText("DEMO BOOKING CONFIRMED").waitFor({ timeout: 4000 })
  await page.goto(BASE + "/account")
  await page.waitForSelector(".app-shell")
  check("no unread left, so the badge is hidden", (await badge.count()) === 0 && (await unread()) === 0)
  await bell.click()
  await items.filter({ hasText: "Booking accepted" }).click()
  check("once paid, the same notice opens the booking details instead", urlIs("/account/bookings/PN-2501-0104") && (await page.getByText("DEMO BOOKING CONFIRMED").count()) === 1, page.url().replace(BASE, ""))
})

section("Mark all as read")
await guard("mark all", async () => {
  await open(page, { signedIn: true, page: "bookings" })
  await bell.click()
  await list.getByRole("button", { name: "Mark all as read" }).click()
  check("the count drops to zero", (await unread()) === 0 && (await badge.count()) === 0)
  check("every notice looks read", (await list.locator(".notice.unread").count()) === 0)
  check("the button disappears when nothing is unread", (await list.getByRole("button", { name: "Mark all as read" }).count()) === 0)
  check("the list stays open", await list.isVisible())
  check("you stay on the same page", urlIs("/account/bookings"))
  await page.reload()
  await page.waitForSelector(".app-shell")
  check("still read after a refresh", (await unread()) === 0)
  const s = await state()
  check("only this role's notices change", s.notices.filter((n) => n.role !== "customer").some((n) => !n.read))
})

section("New notifications")
await guard("new message", async () => {
  await open(page, { signedIn: true, page: "messages" })
  await page.locator(".conversation-list button", { hasText: "PujaNow Support" }).click()
  await page.getByLabel("Write a message").fill("Can I change the samagri delivery time?")
  await page.getByLabel("Send message").click()
  await page.locator(".conversation-list button", { hasText: "Acharya Raghav" }).click()
  await page.waitForTimeout(1900)
  check("a reply in another conversation adds a notification", (await unread()) === 3 && (await badge.textContent()) === "3", String(await unread()))
  await bell.click()
  const n = items.first()
  check("it is titled New message and names the sender", (await n.locator("b").textContent()) === "New message" && (await n.textContent()).includes("PujaNow Support sent you a new message"))
  check("its time is now", (await n.locator("small").textContent()).startsWith("Today"))
  await n.click()
  check("it opens that conversation", (await page.locator(".chat-person b").textContent()) === "PujaNow Support")
  await page.getByLabel("Write a message").fill("Thank you")
  await page.getByLabel("Send message").click()
  await page.waitForTimeout(1900)
  check("a reply in the conversation you are reading adds none", (await unread()) === 2, String(await unread()))
})
await guard("booking events", async () => {
  await open(page, { role: "pandit", signedIn: true, page: "requests" })
  const before = (await state()).notices.length
  await page.locator(".request-rows > div", { hasText: "Ritika" }).getByRole("button", { name: "Accept" }).click()
  check("accepting adds no notice for the pandit themselves", (await unread()) === 2)
  check("the change is recorded for the admin", (await state()).notices.length === before + 1)
  await bell.click()
  check("pandit notices show titles too", (await items.first().locator("b").textContent()) === "New booking requests")
  await items.filter({ hasText: "payout" }).click()
  check("a payout notice opens Earnings", urlIs("/partner/earnings"))
})
await guard("old saved notices", async () => {
  await open(page, { signedIn: true, page: "dashboard", notices: [{ id: "old", role: "customer", text: "Saved before titles existed", page: "bookings", read: false }] })
  await bell.click()
  const n = items.first()
  check("an older notice without a title or time still shows", (await n.locator("b").textContent()) === "Booking update" && (await n.locator("small").count()) === 0)
  await n.click()
  check("and still opens its page", urlIs("/account/bookings"))
})

section("Admin")
await guard("admin", async () => {
  await open(page, { role: "admin", signedIn: true, page: "admin-overview" })
  check("admin sees their own count", (await unread()) === 2)
  await bell.click()
  await items.filter({ hasText: "complaint" }).click()
  check("a complaint notice opens complaints", urlIs("/admin/complaints"))
})

section("Phone")
await guard("phone", async () => {
  await page.setViewportSize({ width: 390, height: 844 })
  await open(page, { signedIn: true, page: "dashboard" })
  check("the bell is visible on a phone", await bell.isVisible())
  await bell.click()
  const box = await list.boundingBox()
  check("the list fits the screen", box.x >= 0 && box.x + box.width <= 390 && box.y + box.height <= 844, JSON.stringify(box))
  await page.mouse.click(200, 700)
  check("tapping outside closes it", (await list.count()) === 0)
  await bell.click()
  await items.filter({ hasText: "Booking accepted" }).click()
  check("a notice opens its page on a phone", urlIs("/account/bookings/PN-2501-0104/pay"))
  const over = await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)
  check("no sideways scrolling", over === 0, String(over))
})

finish()
await browser.close()
