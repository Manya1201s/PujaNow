// The approval-before-payment workflow, its expiry rules, and real URLs.
import { BASE, isBusy, isoDate, KEY, launch, open, reporter, urlFor, writeState } from "./helpers.mjs"

const { browser, page, errors, ctx } = await launch()
page.setDefaultTimeout(9000)
const { check, section, finish } = reporter(errors, "Workflow")
const btn = (name) => page.getByRole("button", { name, exact: true })
const has = async (s) => (await page.getByText(s, { exact: false }).count()) > 0
const state = () => page.evaluate((k) => JSON.parse(localStorage.getItem(k)), KEY)
const field = (label) => page.getByLabel(new RegExp("^\\s*" + label))
const booking = async (id) => (await state()).bookings.find((b) => b.id === id)
const urlIs = (path) => page.url() === BASE + path
// Opens a URL and gives any redirect a moment to update the address bar.
const visit = async (path) => {
  await page.goto(BASE + path)
  await page.waitForSelector("#root > *")
  await page.waitForTimeout(120)
}
const guard = async (name, fn) => {
  try {
    await fn()
  } catch (e) {
    check(`${name} (no crash)`, false, e.message.split("\n").slice(0, 2).join(" ").slice(0, 220))
  }
}
// Saves state while the app is not loaded, then returns to the same page.
const saveState = async (p) => {
  const back = page.url()
  await writeState(page, p)
  await page.goto(back)
  await page.waitForSelector("#root > *")
}
async function asRole(role, target, extra = {}) {
  await saveState({ role, signedIn: true, ...extra })
  await page.goto(urlFor({ page: target, role, bookingId: extra.bookingId }))
  await page.waitForSelector("#root > *")
}
const openBooking = async (id, target = "confirmation") => {
  await saveState({ role: "customer", signedIn: true })
  await page.goto(urlFor({ page: target, role: "customer", bookingId: id }))
  await page.waitForSelector("#root > *")
}
/** Days ahead when this pandit is free. */
const freeDate = (panditId, from = 20) => {
  const d = new Date(Date.now() + from * 864e5)
  while (isBusy(panditId, isoDate(d))) d.setDate(d.getDate() + 1)
  return isoDate(d)
}
/** Goes through the customer steps and sends a request with the default pandit. */
async function sendRequest(pujaName = "Griha Pravesh Puja") {
  await open(page, { page: "explore" })
  await page.locator(".puja-card", { hasText: pujaName }).click()
  await btn("Find an available pandit").click()
  await page.locator(".pandit-card", { hasText: "Acharya Raghav" }).getByRole("button", { name: "View profile" }).click()
  await btn("Check availability").click()
  const date = freeDate("raghav")
  await saveState({ draft: { ...(await state()).draft, date, time: null } })
  await page.reload()
  await page.locator(".time-slots button").first().waitFor()
  const time = await page.locator(".time-slots button span").first().textContent()
  await page.locator(".time-slots button").first().click()
  await btn("Continue to details").click()
  await btn("Send booking request").click()
  await page.getByText("REQUEST SENT").waitFor()
  return { id: (await state()).bookings[0].id, date, time }
}
