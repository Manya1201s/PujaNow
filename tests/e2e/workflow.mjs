await guard("deadline before puja", async () => {
  await open(page, { page: "booking" })
  await ctx.clock.setFixedTime(new Date(new Date().setHours(9, 0, 0, 0)))
  const today = isoDate(new Date(new Date().setHours(9, 0, 0, 0)))
  if (!isBusy("raghav", today)) {
    await saveState({ draft: { ...(await state()).draft, date: today, time: null } })
    await page.reload()
    await page.locator(".time-slots button").first().click()
    await btn("Continue to details").click()
    await btn("Send booking request").click()
    await page.getByText("REQUEST SENT").waitFor()
    const b = (await state()).bookings[0]
    check("a same-day request must be answered before the puja starts", new Date(b.expiresAt).getTime() <= new Date(new Date().setHours(18, 0, 0, 0)).getTime(), `${b.time}, due ${new Date(b.expiresAt).toLocaleTimeString()}`)
  } else check("a same-day request must be answered before the puja starts (pandit busy today)", true)
  await ctx.clock.setFixedTime(new Date())
})

